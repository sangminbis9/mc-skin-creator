export type MessageKey = keyof typeof messages;
type MessageValues = Readonly<Record<string, string | number>>;
export type Translator = (key: MessageKey, values?: MessageValues) => string;

export function translate(language: Language, key: MessageKey, values?: MessageValues): string {
  const message = messages[key][language === "ko" ? 0 : 1] as string;
  return values ? message.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token)) : message;
}
